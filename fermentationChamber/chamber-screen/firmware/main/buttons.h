/*
 * buttons.h - debounced input for the four front-panel buttons and the
 * door switch.
 *
 * Polled rather than interrupt-driven: GPIO 35/36/39 are input-only with no
 * internal pull-ups, the stock firmware polls them too, and at human button
 * speeds polling is simpler to reason about than debouncing in an ISR.
 *
 * Long-press is reported separately because the stock UI depends on it -
 * "To exit, hold back for a few seconds" in the input test, and long-press
 * select to finish text entry.
 */

#pragma once

#include <stdbool.h>
#include <stdint.h>
#include "esp_err.h"

typedef enum {
    BTN_UP = 0,
    BTN_DOWN,
    BTN_SELECT,
    BTN_BACK,
    BTN_DOOR,        /* a switch, not a button - level matters, not edges */
    BTN_COUNT
} button_t;

typedef enum {
    BTN_EVENT_PRESSED = 0,
    BTN_EVENT_RELEASED,
    BTN_EVENT_LONG_PRESS,
} button_event_type_t;

typedef struct {
    button_t            button;
    button_event_type_t type;
    uint32_t            held_ms;   /* for RELEASED and LONG_PRESS */
} button_event_t;

esp_err_t buttons_init(void);

/*
 * Pop the next event, or return false if none is pending.
 * Call from your main loop; events are generated by an internal poll task.
 */
bool buttons_poll(button_event_t *out, uint32_t wait_ms);

/* Instantaneous debounced state. */
bool buttons_is_down(button_t b);

/* Convenience: the door switch is a level, not an event. */
bool buttons_door_is_open(void);

const char *buttons_name(button_t b);
